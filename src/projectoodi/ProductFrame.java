    private void deleteProductBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteProductBtnActionPerformed

        try {

        int row = tblRemove.getSelectedRow();

        if(row == -1) {

            throw new Exception(
                    "Please select a Product.");
        }

        String productId = tblRemove.getValueAt(row, 0).toString();
        
        int confirm =
                JOptionPane.showConfirmDialog(
                        null,
                        "Are you sure you want to delete?",
                        "Confirm Delete",
                        JOptionPane.YES_NO_OPTION);

        if(confirm != JOptionPane.YES_OPTION) {
            return;
        }
        
        java.sql.Connection conn = DBConnection.getConnection();
        if (conn != null) {
            String sql = "DELETE FROM products WHERE product_id = ?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, productId);

            int rowsDeleted = pst.executeUpdate();
            if (rowsDeleted > 0) {
                JOptionPane.showMessageDialog(this, "Product Deleted Successfully from Database.");
            } else {
                JOptionPane.showMessageDialog(this, "Product ID not found in database.");
            }

            pst.close();
            conn.close(); // Tutup sambungan database
        } else {
            throw new Exception("Database connection failed!");
        }

        DefaultTableModel model =
                (DefaultTableModel)
                tblRemove.getModel();

        model.removeRow(row);

        BufferedWriter writer =
                new BufferedWriter(
                        new FileWriter(
                                "product.txt"));

        for(int i = 0;
            i < model.getRowCount();
            i++) {

            writer.write(
                    model.getValueAt(i,0).toString() + "," +
                    model.getValueAt(i,1).toString() + "," +
                    model.getValueAt(i,2).toString() + "," +
                    model.getValueAt(i,3).toString() 
            );

            writer.newLine();
        }

        writer.close();



        

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                null,
                e.getMessage(),
                "Delete Error",
                JOptionPane.ERROR_MESSAGE);
    }
    
    loadProductData();
    loadViewData();
    loadDeleteProduct();
    
    }//GEN-LAST:event_deleteProductBtnActionPerformed

