            String sql = "UPDATE products SET product_name = ?, quantity = ?, price_unit = ? WHERE product_id = ?";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, productName);
            pst.setInt(2, Integer.parseInt(productQty));
            pst.setInt(3, Integer.parseInt(productPrice));
            pst.setString(4, productId);
           

