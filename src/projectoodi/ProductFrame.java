        model.setValueAt(txtproductName1.getText(), row, 1);
        model.setValueAt(txtproductQty1.getText(), row, 2);
        model.setValueAt(txtprice1.getText(), row , 3);


        saveTableToFile();


        loadProductData();
        loadViewData();
        loadDeleteProduct();
        clearFields();
