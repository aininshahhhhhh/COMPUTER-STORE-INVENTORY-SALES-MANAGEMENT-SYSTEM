    private void saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveActionPerformed
        try {
            String productId = txtproductId.getText().trim();
            String productName = txtproductName.getText().trim();
            String productQty = txtproductQty.getText().trim();
            String productPrice = txtprice.getText().trim();

            if (productId.isEmpty() || productName.isEmpty() || productQty.isEmpty() || productPrice.isEmpty()) {        
                throw new Exception("Please fill all fields!");
            }

            java.sql.Connection conn = DBConnection.getConnection();
        if (conn != null) {
            // Arahan SQL untuk masukkan data ke table products
            String sql = "INSERT INTO products (product_id, product_name, quantity, price_unit) VALUES (?, ?, ?, ?)";
            java.sql.PreparedStatement pst = conn.prepareStatement(sql);
            
            pst.setString(1, productId);
            pst.setString(2, productName);
            pst.setInt(3, Integer.parseInt(productQty));
            pst.setDouble(4, Double.parseDouble(productPrice));

            int rowsInserted = pst.executeUpdate();
            if (rowsInserted > 0) {
                JOptionPane.showMessageDialog(this, "Product Saved Successfully to Database!");
            }
            
            pst.close();
            conn.close(); // Tutup sambungan
            
        } else {
            throw new Exception("Database connection failed!");
        }
        
            File file = new File("product.txt");
            BufferedWriter writer = new BufferedWriter(new FileWriter(file, true));
            
            
            writer.write(productId + "," + productName + "," + productQty + "," + productPrice);
            writer.newLine();
            writer.close();

            loadProductData(); 
            loadDeleteProduct();
            clearFields();

        
        }
        catch(Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
                                        

    
    }//GEN-LAST:event_saveActionPerformed

